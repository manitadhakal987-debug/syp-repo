from django.db import models
from django.contrib.auth.models import User

class HairProfile(models.Model):
    CURL_CHOICES = [
        ('2A', '2A - Loose, gentle waves'),
        ('2B', '2B - Defined, S-shaped waves'),
        ('2C', '2C - Deep distinct waves, high texture'),
        ('3A', '3A - Large, bouncy spiral curls'),
        ('3B', '3B - Tight springy ringlets'),
        ('3C', '3C - Dense corkscrew curls'),
        ('4A', '4A - Dense S-pattern mini coils'),
        ('4B', '4B - Sharp Z-pattern zigzag coils'),
        ('4C', '4C - Tightest afro coils, high shrinkage'),
    ]

    POROSITY_CHOICES = [
        ('low', 'Low Porosity (Water beads up, slow to get wet & slow to dry, prone to buildup)'),
        ('medium', 'Medium Porosity (Balanced moisture absorption and retention)'),
        ('high', 'High Porosity (Absorbs water instantly, dries fast, prone to frizz and gaps)'),
    ]

    DENSITY_CHOICES = [
        ('fine', 'Fine Strands (Hair is thin and easily weighed down)'),
        ('medium', 'Medium Strands (Hair has moderate thickness and volume)'),
        ('coarse', 'Coarse / Thick Strands (Thick individual strands, highly resilient)'),
    ]

    SCALP_CHOICES = [
        ('oily', 'Oily Scalp (Becomes greasy within 1-2 days)'),
        ('normal', 'Balanced / Normal Scalp (Clean and comfortable for several days)'),
        ('dry', 'Dry Scalp (Feels tight, itchy or occasionally flakes)'),
        ('sensitive', 'Sensitive Scalp (Easily irritated by harsh scents or sulfates)'),
    ]

    BUDGET_CHOICES = [
        ('budget', 'Budget-Friendly (Under NPR 1,000 per product)'),
        ('mid', 'Mid-Range (NPR 1,000 – NPR 2,500 per product)'),
        ('premium', 'Premium Care (NPR 2,500+ salon-grade curls)'),
    ]

    user = models.ForeignKey(User, on_delete=models.CASCADE, null=True, blank=True, related_name='hair_profiles')
    session_key = models.CharField(max_length=100, blank=True, null=True)
    
    curl_type = models.CharField(max_length=5, choices=CURL_CHOICES, default='3B')
    porosity = models.CharField(max_length=10, choices=POROSITY_CHOICES, default='medium')
    density = models.CharField(max_length=10, choices=DENSITY_CHOICES, default='medium')
    scalp_type = models.CharField(max_length=15, choices=SCALP_CHOICES, default='normal')
    concerns = models.CharField(
        max_length=255,
        default='frizz,dryness',
        help_text="Comma-separated concerns: frizz,dryness,breakage,dandruff,lack_of_volume,heat_damage"
    )
    budget = models.CharField(max_length=15, choices=BUDGET_CHOICES, default='mid')
    
    # Cached Diagnosis generated by the rule engine
    diagnosis_title = models.CharField(max_length=255, blank=True)
    diagnosis_summary = models.TextField(blank=True)
    
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        user_str = self.user.username if self.user else f"Guest ({self.session_key[:8] if self.session_key else 'anon'})"
        return f"{user_str} - {self.curl_type} ({self.get_porosity_display().split(' ')[0]} Porosity)"

    @property
    def curl_family(self):
        if self.curl_type.startswith('2'):
            return 'Wavy'
        elif self.curl_type.startswith('3'):
            return 'Curly'
        elif self.curl_type.startswith('4'):
            return 'Coily / Kinky'
        return 'Curly'

    @property
    def concerns_list(self):
        if not self.concerns:
            return []
        return [c.strip() for c in self.concerns.split(',') if c.strip()]
